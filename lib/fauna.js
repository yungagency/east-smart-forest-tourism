export function getAnimal(slug) {
  return FAUNA.find((a) => a.slug === slug) || null;
}

export function faunaForSite(siteSlug) {
  return FAUNA.filter((a) => a.sites.includes(siteSlug));
}

export function tf(o, f, lang) {
  return o?.[`${f}_${lang}`] || o?.[`${f}_fr`] || '';
}

